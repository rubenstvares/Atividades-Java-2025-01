public class Atividade07 {
    public static void main(String[] args) {
        // Declaração da variável contador
        int cont = 101;  // Começamos do número 101, pois 100 não será impresso

        // Laço while para imprimir os números entre 100 e 200
        while (cont < 200) {
            System.out.println("Contagem: " + cont);
            cont++;  // Incrementa 1 ao contador
        }
    }
}

public class atividade03 {
    public static void main(String[] args) {
        // Declaração das variáveis
        int a;           // Tipo inteiro
        double b;        // Tipo real (números de ponto flutuante)
        char c;          // Tipo caractere
        boolean d;       // Tipo booleano

        // Atribuindo valores às variáveis
        a = 7;
        b = 5.23;
        c = 'B';         // Usando um caractere único
        d = true;        // Pode ser verdadeiro (true) ou falso (false)

        // Exibindo os valores das variáveis
        System.out.println("Este é meu número Inteiro: " + a);
        System.out.println("Este é meu número Real: " + b);
        System.out.println("Este é meu caractere: " + c);
        System.out.println("Este é meu valor booleano: " + d);
    }
}
